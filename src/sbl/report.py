"""Run the monitoring queries and write the results to a Markdown file.

    python -m sbl.report --env local --out docs/run-results.md
    python -m sbl.report --env databricks --render-sql     # print the SQL for a dashboard

Every number in docs/run-results.md comes from this script querying the tables.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import UTC, datetime
from importlib.resources import files

from sbl.config import known_tables, load_config
from sbl.lakehouse import Lakehouse

OPS_TABLES = ["ops.audit_runs", "ops.ingested_files", "ops.quarantine", "ops.watermarks",
              "ops.dq_results", "ops.reconciliation"]


def load_queries() -> dict[str, str]:
    text = files("sbl").joinpath("sql/monitoring.sql").read_text(encoding="utf-8")
    queries = {}
    for block in re.split(r"^-- name: ", text, flags=re.M)[1:]:
        name, body = block.split("\n", 1)
        sql = "\n".join(line for line in body.splitlines() if not line.startswith("--"))
        queries[name.strip()] = sql.strip().rstrip(";")
    return queries


def render(sql: str, lh: Lakehouse) -> str:
    return re.sub(r"\{(\w+)\.(\w+)\}", lambda m: lh.ref(m.group(1), m.group(2)), sql)


def to_markdown(rows, columns) -> str:
    def fmt(v):
        if isinstance(v, float):
            return f"{v:,.6g}" if abs(v) < 1e6 else f"{v:,.0f}"
        return str(v).replace("|", "\\|") if v is not None else ""
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def table_inventory(lh: Lakehouse, cfg) -> list[tuple]:
    rows = []
    for qualified in sorted(known_tables(cfg)) + OPS_TABLES:
        layer, name = lh.split(qualified)
        if lh.exists(layer, name):
            version = lh.delta(layer, name).history(1).select("version").first()[0]
            rows.append((qualified, lh.read(layer, name).count(), version))
    return rows


def build_report(lh: Lakehouse, cfg) -> str:
    out = [
        "# Pipeline run results",
        "",
        f"Generated by `python -m sbl.report` on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC "
        "from the tables themselves. Do not edit by hand.",
        "",
        "## Tables",
        "",
        to_markdown(table_inventory(lh, cfg), ["table", "rows", "latest Delta version"]),
    ]
    for name, sql in load_queries().items():
        out += ["", f"## {name}", ""]
        try:
            df = lh.sql(render(sql, lh))
            out.append(to_markdown([tuple(r) for r in df.collect()], df.columns))
        except Exception as exc:  # e.g. no quarantine table because nothing was quarantined
            out.append(f"_Query failed: {type(exc).__name__}: {str(exc).splitlines()[0]}_")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--env", default="local")
    parser.add_argument("--catalog")
    parser.add_argument("--out", default="docs/run-results.md")
    parser.add_argument("--render-sql", action="store_true", help="print SQL only; no Spark")
    args = parser.parse_args(argv)
    cfg = load_config(args.env, catalog=args.catalog)

    if args.render_sql:
        lh = Lakehouse(None, cfg.env)
        for name, sql in load_queries().items():
            print(f"-- {name}\n{render(sql, lh)};\n")
        return 0

    from sbl.spark import get_spark
    lh = Lakehouse(get_spark(args.env), cfg.env)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(build_report(lh, cfg))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
